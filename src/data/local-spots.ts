export function getSpotsByCategory(category: SpotCategory): LocalSpot[] {
  return localSpots.filter((s) => s.category === category);
}

export function getVisibleSpots(now: Date = new Date()): LocalSpot[] {
  const today = now.toISOString().split("T")[0];
  return localSpots.filter((spot) => {
    if (!spot.eventDates) return true;
    return today >= spot.eventDates.showFrom && today <= spot.eventDates.hideAfter;
  });
}

export function getFeaturedSpots(): LocalSpot[] {
  return localSpots.filter((s) => s.featured);
}

